import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
const html=fs.readFileSync('index.html','utf8');
const script=html.match(/<script>\s*([\s\S]*?)<\/script>/)[1];
new vm.Script(script);
const source=script.slice(script.indexOf('function econ('),script.indexOf('function params('));
const econ=vm.runInNewContext(source+';econ');
const p={view:'3p',fee:15,hr:22,ai:.4,vf:3,ex:20,masc:false};
const s={k:'wa',b:1800,rh:30,rv:33,lh:0,lv:0,lift:0,t:6};
const r=econ(s,p);
assert.ok(Math.abs(r.h-67.8)<1e-8);
assert.ok(Math.abs(r.v-66.24)<1e-8);
assert.equal(econ({...s,k:'bl',rv:100},p).vMin,10);
assert.ok(econ({...s,k:'bl',rv:100},p).v<0);
assert.equal(econ({...s,k:'bl'},p).h,0);
const high=econ({...s,b:100,rh:100,lh:100,lift:100,t:0},{...p,view:'1p'});
assert.ok(high.h<=100);
assert.ok(econ({...s,lv:45,lift:22},{...p,masc:true}).v>econ({...s,lv:45,lift:22},p).v);
console.log('Model checks passed');
